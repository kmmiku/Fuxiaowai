const {test}=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs/promises');
const os=require('node:os');
const path=require('node:path');
const http=require('node:http');
const {createAdminConsole}=require('../server/admin-console');
test('update publication enforces authentication, origin, validation, persistence and withdrawal',async t=>{
 const root=await fs.mkdtemp(path.join(os.tmpdir(),'fxw-update-'));
 const json=(req,res,status,data)=>{res.writeHead(status,{'content-type':'application/json'});res.end(JSON.stringify(data));};
 const opts={ROOT:root,TICKET_DIR:root,TTL_MS:1,PORT:0,BIND:'127.0.0.1',json,checkAuth:r=>r.headers.authorization==='test-only',needAuth:(req,res)=>json(req,res,401,{}),externalProbe:false};
 let admin=createAdminConsole(opts);
 const server=http.createServer(async(req,res)=>{if(!await admin.handle(req,res,new URL(req.url,'http://localhost')))json(req,res,404,{});});
 await new Promise(r=>server.listen(0,'127.0.0.1',r));
 t.after(async()=>{await new Promise(r=>server.close(r));await admin.close();await fs.rm(root,{recursive:true,force:true});});
 const base='http://127.0.0.1:'+server.address().port;
 const request=(route,method='GET',body,extra={})=>fetch(base+route,{method,headers:{authorization:'test-only','content-type':'application/json',...extra},body:body===undefined?undefined:JSON.stringify(body)});
 assert.equal((await fetch(base+'/api/admin/app-update')).status,401);
 assert.equal((await (await request('/api/app-update')).json()).release,null);
 const release={versionCode:1000002,versionName:'0.1.2',content:'<script>plain text</script>\n修复问题'};
 assert.equal((await request('/api/admin/app-update','PUT',release,{origin:'https://evil.example'})).status,403);
 assert.equal((await request('/api/admin/app-update','PUT',{...release,versionCode:1.5})).status,400);
 assert.equal((await request('/api/app-update','PUT',release)).status,405);
 assert.equal((await request('/api/admin/app-update','PUT',release)).status,200);
 await admin.close();admin=createAdminConsole(opts);
 const response=await fetch(base+'/api/app-update');assert.equal(response.headers.get('cache-control'),'no-store');
 const data=await response.json();assert.equal(data.release.versionCode,1000002);assert.equal(data.release.content,release.content);
 assert.equal((await request('/api/admin/app-update','DELETE')).status,200);
 assert.equal((await (await request('/api/app-update')).json()).release,null);
});
